<p>Ask any visualization artist what makes a project run smoothly and they will say the same thing: a good brief. A first draft is only as good as the information behind it. When the brief is thin, the artist guesses, you correct, and each correction costs a day.</p>
<p>This checklist shows <strong>how to brief a rendering team</strong> so the first draft lands close to what you had in mind.</p>

<h2>Start with the purpose of the image</h2>
<p>Before any file is sent, answer one question: what is this image for? A planning submission, a client presentation, a sales brochure and a social post all call for different looks. Tell the team who will see it and what you want them to feel or decide. One sentence is enough: "This is for a homeowner deciding between two kitchen layouts."</p>

<h2>Send the right source files</h2>
<ul>
<li><strong>Drawings:</strong> plans, sections and elevations in DWG or a clear PDF, with dimensions and levels.</li>
<li><strong>A 3D model</strong> if you have one (Revit, SketchUp, Rhino), plus a note about which parts are final.</li>
<li><strong>Site information:</strong> photos of the surroundings, orientation and any context that must appear.</li>
<li><strong>Material and product choices:</strong> finish schedules, product links or sample photos.</li>
</ul>
<p>If the files are incomplete, say so. It is far better to flag "the roof is not final" than to have it modeled and redone.</p>

