<h2>Show, do not only tell</h2>
<p>Words like "modern", "warm" or "luxurious" mean different things to different people. Three to six reference images communicate more than a page of adjectives. For each one, add a short note on what you like about it: the light, the material palette, the camera angle, the level of greenery.</p>
<p>It also helps to include one example of what you do <em>not</em> want. Rejecting a style early is quicker than correcting it later.</p>

<h2>Define the camera</h2>
<p>Mark the viewpoint on a plan or sketch. Mention the height (eye-level, raised, aerial), the direction, and anything that must be in or out of frame. For interiors, say which wall or feature is the focus.</p>

<h2>Describe the light and atmosphere</h2>
<ul>
<li>Time of day: bright midday, soft morning, dusk with interior lights on.</li>
<li>Weather and season: clear sky, overcast, autumn leaves.</li>
<li>Mood: calm and minimal, lively and populated, dramatic and moody.</li>
</ul>
<p>A dusk image with glowing windows is a very different job from a bright daytime view, so choose deliberately.</p>

<h2>Give practical details</h2>
<ul>
<li><strong>Format and size:</strong> screen only, or print? Landscape or portrait?</li>
<li><strong>Deadline:</strong> including any hard presentation date.</li>
<li><strong>Revisions:</strong> how many rounds are included, and who approves each stage.</li>
<li><strong>Confidentiality:</strong> whether an NDA is needed.</li>
</ul>

<h2>Plan the feedback process</h2>
<p>A simple order of approval keeps everyone calm and keeps costs down:</p>
<ol>
<li><strong>Massing and camera</strong> - is the shape, view and composition right?</li>
<li><strong>Materials and furnishing</strong> - are the finishes and objects correct?</li>
<li><strong>Lighting and mood</strong> - is the atmosphere what you want?</li>
<li><strong>Final polish</strong> - small corrections only.</li>
</ol>
<p>Combine all comments for each stage into one message, mark them on the image if you can, and avoid reopening decisions that were already approved.</p>

<blockquote><p>The best briefs are not long. They are specific: one purpose, a few strong references, a marked camera and a clear deadline.</p></blockquote>

<h2>A one-page brief template</h2>
<p>If you want a shortcut, copy this into an email:</p>
<ul>
<li>Project and purpose of the image</li>
<li>Files attached, and what is final or not</li>
<li>Views required, with camera marked</li>
<li>Three to six references, with notes</li>
<li>Time of day, mood and season</li>
<li>Size, format and deadline</li>
</ul>

