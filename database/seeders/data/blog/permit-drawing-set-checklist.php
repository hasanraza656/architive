<h2>1. Cover sheet and project information</h2>
<ul>
<li>Project address, parcel or lot number and project description.</li>
<li>Applicant and designer details, and any required licence or stamp areas.</li>
<li>Sheet index listing every drawing in the set.</li>
<li>Applicable codes and key project data such as occupancy, construction type and areas.</li>
</ul>

<h2>2. Site plan</h2>
<ul>
<li>Property boundaries, setbacks and easements, with dimensions.</li>
<li>Existing and proposed buildings, driveways, walkways and parking.</li>
<li>North arrow and scale.</li>
<li>Utilities and drainage where the authority requires them.</li>
</ul>

<h2>3. Floor plans</h2>
<ul>
<li>Existing plans and proposed plans, clearly distinguished (for example, existing, to be demolished, new).</li>
<li>Overall and room dimensions, wall types and openings.</li>
<li>Room names, door and window tags, and area figures.</li>
<li>Stairs, egress paths and required clearances.</li>
</ul>

