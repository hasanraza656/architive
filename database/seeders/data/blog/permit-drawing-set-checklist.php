<li>Compare your set to the department's checklist, line by line.</li>
<li>Check that dimensions and tags are consistent across sheets.</li>
<li>Print or preview at the required size to confirm text is readable.</li>
<li>Ask someone who did not draw the set to review it with fresh eyes.</li>
</ul>

