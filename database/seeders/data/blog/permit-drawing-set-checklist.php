<h2>4. Elevations and sections</h2>
<ul>
<li>All sides of the building with materials, heights and roof pitches.</li>
<li>At least one building section showing floor-to-floor heights, ceiling heights and key assemblies.</li>
<li>Wall sections or typical details where the reviewer needs to see construction.</li>
</ul>

<h2>5. Structural and framing information</h2>
<ul>
