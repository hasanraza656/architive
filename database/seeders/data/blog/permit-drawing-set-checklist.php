<li><strong>Missing items</strong> such as egress, smoke alarms or energy notes.</li>
<li><strong>Illegible text</strong> because sheets were scaled down or scanned poorly.</li>
<li><strong>Sheet numbers and references out of sync</strong> with the index.</li>
</ol>

<h2>Before you submit</h2>
