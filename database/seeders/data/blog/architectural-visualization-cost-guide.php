<h2>How studios usually price the work</h2>
<ul>
<li><strong>Per image.</strong> A fixed fee for a defined view, common for single exteriors or interiors. Easy to compare, but make sure it states the revision rounds.</li>
<li><strong>Per project package.</strong> A bundle, for example several views of one scheme, sometimes with an animation or a 3D floor plan. Best value when you know your full needs.</li>
<li><strong>Hourly.</strong> Suited to changing scope, ongoing support or work where you cannot define the end point yet. You pay for time, so a clear brief and fast feedback matter most.</li>
</ul>
<p>None of these is "right". Fixed fees give budget certainty; hourly gives flexibility. Many teams use a fixed fee for a defined set of images and an hourly arrangement for anything that comes later.</p>

<h2>How to get an accurate quote</h2>
<p>You will get a tighter, fairer number if you send the same information to every studio. At a minimum:</p>
<ol>
<li>The drawings or model you will provide, and their format (DWG, PDF, Revit, SketchUp).</li>
<li>The number of views and the type of each (exterior, interior, aerial, 3D floor plan).</li>
<li>Reference images that show the look you want.</li>
<li>The deadline, and any fixed presentation date.</li>
<li>How the images will be used and at what size.</li>
</ol>
<blockquote><p>A precise brief does not just lower the quote. It lowers the number of times you will say "that is not what I meant".</p></blockquote>

<h2>Sensible ways to spend less without lowering quality</h2>
<ul>
<li>Lock the design before you start. Changing the building mid-render is the most common cause of overruns.</li>
<li>Send consolidated feedback in one message per round, not as a stream of small notes.</li>
<li>Reuse the model for several views, or for a later animation.</li>
<li>Use a simpler style for early reviews and keep the high-end finish for the final marketing image.</li>
<li>Ask what is included. Furniture libraries, landscaping and people are sometimes extras.</li>
</ul>

<h2>Red flags in a quote</h2>
<p>Be cautious when a quote does not state the number of revision rounds, does not say who owns the final files, or is dramatically lower than the others with no explanation. A low price that excludes revisions often ends up costing more than a clear, slightly higher one.</p>

